import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const manage=read('src/components/ManagePage.vue')
const feed=read('src/components/FamilyApprovalFeed.vue')
const policies=read('src/components/RecurringFinancePolicyCenter.vue')
const server=read('worker/recurring-finance-policies.js')
const member=read('src/components/CrossMemberTransferConsents.vue')

test('one flat five-row owner-only approval list replaces nested tabs, duplicate cards and long help copy',()=>{
 const family=manage.slice(manage.indexOf('id="management-family-panel"'))
 assert.match(family,/<FamilyApprovalFeed v-if="active&&isOwner"/)
 assert.doesNotMatch(family,/approvalSection|management-approval-tabs|family-approval-recurring-tab/)
 assert.doesNotMatch(family,/<CrossMemberTransferConsents|<RecurringFinancePolicyCenter|<ApprovalCenter/)
 assert.match(feed,/aria-label="家庭审批列表"/)
 assert.match(feed,/const pageSize=5/)
 assert.match(feed,/\/api\/household-approvals\?page=/)
 assert.match(feed,/page_size!==pageSize/)
 assert.match(feed,/v-for="row in rows"/)
 assert.match(feed,/上一页/)
 assert.match(feed,/下一页/)
 assert.doesNotMatch(feed,/role="tablist"/)
 assert.doesNotMatch(feed,/按钮.*展开|查看授权/)
 assert.match(feed,/batchOpen/)
})
test('member confirmation remains in the private personal tab and cannot see admin approval list',()=>{
 const personal=manage.slice(manage.indexOf('id="management-personal-panel"'),manage.indexOf('id="management-family-panel"'))
 assert.match(personal,/<MemberConfirmationInbox v-if="active&&!isOwner"/)
 assert.match(personal,/<MemberConfirmationInbox v-if="active&&!isOwner"/)
 assert.doesNotMatch(personal,/<RecurringFinancePolicyCenter|<CrossMemberTransferConsents|<ApprovalCenter/)
 assert.match(member,/if\(x.status==='awaiting_recipient'&&x.recipient_user_id===props.userId\)/)
 assert.match(manage,/if\(!isOwner\)section.value='personal'/)
 assert.match(feed,/if\(!props.active\|\|!props.isOwner\|\|!props.userId\|\|busy.value\)return/)
})
test('recurring financial approval remains once per plan, not each occurrence',()=>{
 assert.match(policies,/approve:'批准整个计划'/)
 assert.match(server,/const previous=action==='revoke'\?'approved':'pending_owner'/)
 assert.match(server,/if\(p.status!==previous\)return invalid\('recurring_policy_not_mutable'\)/)
 assert.match(server,/if\(review&&r!=='owner'\)/)
 assert.match(feed,/仅批准这项计划一次/)
 assert.match(feed,/每期仍须以真实交易凭证独立入账/)
})
